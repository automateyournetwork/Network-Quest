import { readFile, realpath, writeFile, stat } from 'node:fs/promises';
import { dirname, resolve, relative, isAbsolute } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const generatedPath = 'src/content/schema.generated.js';
const typesPath = 'src/content/schema-types.generated.ts';

// A mechanical projection for editor/compiler use. The JSON Schema, including
// conditionals not representable here, remains the runtime authority.
function project(s: any): string {
  if (s.$ref) return s.$ref.split('/').at(-1);
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v: unknown) => JSON.stringify(v)).join(' | ');
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(project).join(' | ');
  if (s.type === 'array') return `(${project(s.items)})[]`;
  if (s.type === 'object') {
    if (!s.properties) return `Record<string, ${project(s.additionalProperties ?? {})}>`;
    return `{ ${Object.entries(s.properties).map(([k, v]) => `${JSON.stringify(k)}${s.required?.includes(k) ? '' : '?'}: ${project(v)};`).join(' ')} }`;
  }
  return ({ integer: 'number', number: 'number', string: 'string', boolean: 'boolean', null: 'null' } as Record<string, string>)[s.type] ?? 'unknown';
}

export async function schemaArtifacts(): Promise<Map<string, string>> {
  const schema = JSON.parse(await readFile(resolve(root, 'content/schemas/content.schema.json'), 'utf8'));
  const ajv = new Ajv2020({ strict: true, allErrors: true, inlineRefs: true, code: { source: true, esm: true } });
  addFormats(ajv);
  const validate = ajv.compile(schema);
  let code = standaloneCode(ajv, validate);
  // Ajv standalone emits static CommonJS helper references even in ESM mode.
  // Convert only those literal module references to static ESM imports for Vite;
  // no runtime compiler, eval, filesystem or dynamic module lookup is shipped.
  const imports = new Map<string, string>();
  code = code.replace(/require\("([^"\n]+)"\)(\.default)?/g, (_match, name: string, defaultExport: string | undefined) => {
    if (!/^(ajv\/dist\/runtime\/|ajv-formats\/dist\/)/.test(name)) throw new Error('Unexpected standalone helper');
    const alias = imports.get(name) ?? `schemaHelper${imports.size}`;
    imports.set(name, alias);
    return defaultExport ? `(${alias}.default?.default ?? ${alias}.default ?? ${alias})` : `(${alias}.default ?? ${alias})`;
  });
  const banner = '// Generated by tools/validate-content.ts --generate; DO NOT EDIT.\n// Copyright 2026 John Capobianco. SPDX-License-Identifier: Apache-2.0\n';
  return new Map([
    [generatedPath, `// @ts-nocheck\n${banner}${[...imports].map(([name, alias]) => `import * as ${alias} from '${name.endsWith('.js') ? name : `${name}.js`}';`).join('\n')}\n${code}\n`],
    ['src/content/schema.generated.d.ts', `${banner}declare const validate: { (data: unknown): boolean; errors?: unknown }; export default validate;\n`],
    [typesPath, `${banner}${Object.entries(schema.$defs).map(([key, value]) => `export type ${key} = ${project(value)};`).join('\n')}\n`],
  ]);
}

export async function loadDocument(repositoryRoot: string, path: string): Promise<unknown> {
  if (!/^content\/spec001\/(?:[A-Za-z0-9_-]+\/)*[A-Za-z0-9_.-]+\.json$/.test(path)) throw new Error('Content path must remain under content/spec001');
  const base = resolve(await realpath(repositoryRoot), 'content/spec001');
  const target = await realpath(resolve(repositoryRoot, path));
  const local = relative(base, target);
  if (local.startsWith('..') || isAbsolute(local)) throw new Error('Content symlink escapes content/spec001');
  if ((await stat(target)).size > 4_194_304) throw new Error('Content document exceeds 4 MiB');
  const bytes = await readFile(target);
  if (bytes.length > 4_194_304) throw new Error('Content document exceeds 4 MiB');
  return JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
}

async function main(): Promise<void> {
  const generate = process.argv.includes('--generate');
  for (const [path, source] of await schemaArtifacts()) {
    if (generate) await writeFile(resolve(root, path), source);
    else if (await readFile(resolve(root, path), 'utf8') !== source) throw new Error(`${path} is stale; run node tools/validate-content.ts --generate`);
  }
  const { validateContent } = await import('../src/content/registry.ts');
  const world = await loadDocument(root, 'content/spec001/world.json');
  const sources = await loadDocument(root, 'content/spec001/sources.json');
  // Validate the envelope before allowing it to choose any file to open.
  const preliminary = validateContent({ world, sources, documents: {}, allowUnloadedDocuments: true });
  if (!preliminary.ok) throw new Error(JSON.stringify(preliminary.issues, null, 2));
  const documents: Record<string, unknown> = Object.create(null);
  for (const path of preliminary.documentPaths) documents[path] = await loadDocument(root, path);
  const result = validateContent({ world, sources, documents });
  if (!result.ok) throw new Error(JSON.stringify(result.issues, null, 2));
  process.stdout.write(`Content validation passed: ${result.roomCount} room identities, ${result.authoredRecordCount} authored records; independent routes: ${result.routes.join(', ')}. Metadata is not playable-content acceptance.\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => { process.stderr.write(`${error instanceof Error ? error.message : 'Content validation failed'}\n`); process.exitCode = 1; });
}
