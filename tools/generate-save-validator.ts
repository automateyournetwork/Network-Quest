import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Build time only. The browser imports static code, never the Ajv compiler. */
export async function saveSchemaArtifacts(): Promise<Map<string, string>> {
  const schema = JSON.parse(await readFile(resolve(root, 'specs/001-physical-layer-underworld/contracts/save.schema.json'), 'utf8'));
  const ajv = new Ajv2020({ strict: true, allowUnionTypes: true, allErrors: false, inlineRefs: true, code: { source: true, esm: true } });
  addFormats(ajv);
  // ajv-formats also accepts a URN prefix and a terminal newline; the contract's
  // UUID format and Opis use the bare 36-character representation. Pin parity.
  ajv.addFormat('uuid', /^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}(?![\s\S])/i);
  const validate = ajv.compile(schema);
  const imports = new Map<string, string>();
  const code = standaloneCode(ajv, validate).replace(/require\("([^"\n]+)"\)(\.default)?/g, (_match, name: string, defaultExport: string | undefined) => {
    if (!/^(ajv\/dist\/runtime\/|ajv-formats\/dist\/)/.test(name)) throw new Error('Unexpected standalone helper');
    const alias = imports.get(name) ?? `saveSchemaHelper${imports.size}`;
    imports.set(name, alias);
    return defaultExport ? `(${alias}.default?.default ?? ${alias}.default ?? ${alias})` : `(${alias}.default ?? ${alias})`;
  });
  const banner = '// Generated by tools/generate-save-validator.ts --generate; DO NOT EDIT.\n// Copyright 2026 John Capobianco. SPDX-License-Identifier: Apache-2.0\n';
  return new Map([
    ['src/services/save-schema.generated.js', `// @ts-nocheck\n${banner}${[...imports].map(([name, alias]) => `import * as ${alias} from '${name.endsWith('.js') ? name : `${name}.js`}';`).join('\n')}\n${code}\n`],
    ['src/services/save-schema.generated.d.ts', `${banner}declare const validate: { (data: unknown): boolean; errors?: unknown }; export default validate;\n`],
  ]);
}

async function main(): Promise<void> {
  for (const [path, source] of await saveSchemaArtifacts()) {
    if (process.argv.includes('--generate')) await writeFile(resolve(root, path), source);
    else if (await readFile(resolve(root, path), 'utf8') !== source) throw new Error(`${path} is stale; run node tools/generate-save-validator.ts --generate`);
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => { process.stderr.write(`${error instanceof Error ? error.message : 'Save schema generation failed'}\n`); process.exitCode = 1; });
}
